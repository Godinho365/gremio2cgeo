"""Sprint 2: catalogação de bens, asset_tag automático, QR, isolamento (Art.30 a)."""
from __future__ import annotations

import pytest
from rest_framework.test import APIClient

from apps.accounts.models import RoleCode
from apps.accounts.services import OnboardingService, UserService
from apps.assets.models import Category
from apps.assets.services import AssetService
from core.context import use_tenant

pytestmark = pytest.mark.django_db


def _org(name: str):
    return OnboardingService().create_organization(
        org_name=name, admin_username=f"admin_{name}", admin_password="supersecret123"
    )


@pytest.fixture
def client() -> APIClient:
    return APIClient()


def test_asset_tag_is_autogenerated_sequentially(tenant_a):
    service = AssetService()
    with use_tenant(tenant_a.id):
        a1 = service.create_asset(name="Notebook")
        a2 = service.create_asset(name="Projetor")
    assert a1.asset_tag.startswith("PAT-")
    assert a1.asset_tag.endswith("000001")
    assert a2.asset_tag.endswith("000002")


def test_create_asset_via_api_with_category(client: APIClient):
    tenant, admin = _org("orgp")
    client.force_authenticate(admin)
    cat = client.post("/api/categories", {"name": "TI"}, format="json")
    assert cat.status_code == 201, cat.data
    resp = client.post(
        "/api/assets",
        {"name": "Notebook Dell", "category": cat.data["id"]},
        format="json",
    )
    assert resp.status_code == 201, resp.data
    assert resp.data["asset_tag"].startswith("PAT-")
    assert resp.data["category_name"] == "TI"


def test_non_manager_cannot_create_category(client: APIClient):
    tenant, admin = _org("orgq")
    with use_tenant(tenant.id):
        plain = UserService().create_user(
            username="plainq", password="supersecret123",
            role_codes=[RoleCode.USER], tenant_id=tenant.id,
        )
    client.force_authenticate(plain)
    resp = client.post("/api/categories", {"name": "X"}, format="json")
    assert resp.status_code == 403


def test_categories_are_tenant_scoped(client: APIClient):
    ta, admin_a = _org("catA")
    tb, admin_b = _org("catB")
    with use_tenant(tb.id):
        Category.objects.create(tenant_id=tb.id, name="Só do B")
    client.force_authenticate(admin_a)
    resp = client.get("/api/categories")
    names = {c["name"] for c in resp.data["results"]}
    assert "Só do B" not in names


def test_cannot_reference_other_tenant_category(client: APIClient):
    ta, admin_a = _org("refA")
    tb, admin_b = _org("refB")
    with use_tenant(tb.id):
        foreign = Category.objects.create(tenant_id=tb.id, name="Alheia")
    client.force_authenticate(admin_a)
    resp = client.post(
        "/api/assets", {"name": "Item", "category": str(foreign.id)}, format="json"
    )
    assert resp.status_code == 400  # category not in tenant A's queryset


def test_edit_asset_updates_status_and_name(client: APIClient):
    tenant, admin = _org("edit")
    client.force_authenticate(admin)
    created = client.post("/api/assets", {"name": "Item"}, format="json").data
    resp = client.patch(
        f"/api/assets/{created['id']}",
        {"name": "Item Renomeado", "status": "maintenance"},
        format="json",
    )
    assert resp.status_code == 200, resp.data
    assert resp.data["name"] == "Item Renomeado"
    assert resp.data["status"] == "maintenance"


def test_qrcode_endpoint_returns_png(client: APIClient):
    tenant, admin = _org("qrorg")
    client.force_authenticate(admin)
    created = client.post("/api/assets", {"name": "Item QR"}, format="json")
    asset_id = created.data["id"]
    resp = client.get(f"/api/assets/{asset_id}/qrcode")
    assert resp.status_code == 200
    assert resp["Content-Type"] == "image/png"
    assert resp.content[:8] == b"\x89PNG\r\n\x1a\n"
